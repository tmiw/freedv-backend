// ---- Tanner graph built from H = [H_a | H_b] ----
struct LDPCGraph {
    struct Edge { int check, var; };

    std::vector<Edge> edges;
    std::vector<int>  check_edges[56];   // edge indices per check node
    std::vector<int>  var_edges[112];    // edge indices per variable node

    LDPCGraph() {
        auto add = [&](int c, int v) {
            int e = (int)edges.size();
            edges.push_back({c, v});
            check_edges[c].push_back(e);
            var_edges[v].push_back(e);
        };

        // H_a edges
        for (int i = 0; i < 56; i++)
            for (int j = 0; j < 56; j++)
                if (H_a[i][j]) add(i, j);

        // H_b edges (lower-bidiagonal):
        //   row 0       : var 56
        //   row i (i≥1) : vars 55+i and 56+i
        add(0, 56);
        for (int i = 1; i < 56; i++) {
            add(i, 55 + i);
            add(i, 56 + i);
        }
    }
};

static const LDPCGraph graph;

// ---- Belief-propagation decoder ----

LDPCDecodeResult ldpc_decode(const RADE_COMP* syms,
                              const float*    amplitudes,
                              float           noise_var,
                              int             max_iter)
{
    constexpr float LLR_MAX = 20.0f;

    if (noise_var < 1e-10f) noise_var = 1e-10f;
    const float scale = 2.0f / noise_var;

    // Compute channel LLRs for diagonal QPSK (RADE native constellation).
    // Mapping: b0 -> I axis (+1 for bit=0, -1 for bit=1), b1 -> Q axis.
    // Separable LLRs: LLR(b0) = a*r_I/σ², LLR(b1) = a*r_Q/σ²
    float llr_ch[112];
    for (int k = 0; k < 56; k++) {
        const float a = amplitudes[k];
        llr_ch[2*k]     = std::clamp(scale * a * syms[k].real, -LLR_MAX, LLR_MAX);
        llr_ch[2*k + 1] = std::clamp(scale * a * syms[k].imag, -LLR_MAX, LLR_MAX);
    }

    const int E = (int)graph.edges.size();

    // m_vc[e]: variable-to-check message on edge e
    // m_cv[e]: check-to-variable message on edge e
    std::vector<float> m_vc(E), m_cv(E, 0.0f);
    for (int e = 0; e < E; e++)
        m_vc[e] = llr_ch[graph.edges[e].var];

    LDPCDecodeResult result{};
    result.converged  = false;
    result.iterations = 0;

    for (int iter = 0; iter < max_iter; iter++) {

        // ---- Check-to-variable update (tanh / sum-product rule) ----
        //
        // For check i and its neighbor set N(i), the outgoing message to
        // variable j is:
        //
        //   r_{i→j} = 2·atanh( ∏_{j'≠j} tanh(q_{j'→i}/2) )
        //
        // Computed using prefix×suffix products to avoid O(d²) complexity.
        // Max check degree is 5, so fixed-size stack arrays are safe.

        for (int i = 0; i < 56; i++) {
            const auto& ce = graph.check_edges[i];
            const int   nd = (int)ce.size();   // 4 or 5 for this code

            // |tanh(v/2)| and sign(v) for each incoming message
            float t[6]; int s[6];
            for (int k = 0; k < nd; k++) {
                const float v = m_vc[ce[k]];
                s[k] = (v >= 0.0f) ? 1 : -1;
                t[k] = std::clamp(std::tanh(std::abs(v) * 0.5f),
                                  1e-10f, 1.0f - 1e-10f);
            }

            // Prefix products (inclusive scan)
            float pf_t[7] = {1.0f}; int pf_s[7] = {1};
            for (int k = 0; k < nd; k++) {
                pf_t[k+1] = pf_t[k] * t[k];
                pf_s[k+1] = pf_s[k] * s[k];
            }
            // Suffix products (exclusive scan from the right)
            float sf_t[7]; sf_t[nd] = 1.0f;
            int   sf_s[7]; sf_s[nd] = 1;
            for (int k = nd - 1; k >= 0; k--) {
                sf_t[k] = sf_t[k+1] * t[k];
                sf_s[k] = sf_s[k+1] * s[k];
            }

            for (int k = 0; k < nd; k++) {
                const float prod = std::clamp(pf_t[k] * sf_t[k+1],
                                              1e-10f, 1.0f - 1e-10f);
                const int   sign = pf_s[k] * sf_s[k+1];
                m_cv[ce[k]] = std::clamp(sign * 2.0f * std::atanh(prod),
                                         -LLR_MAX, LLR_MAX);
            }
        }

        // ---- Variable-to-check update ----
        //
        //   q_{j→i} = λ_j + Σ_{i'≠i} r_{i'→j}
        //
        // Computed as (sum of all incoming check messages + channel LLR) minus
        // the one edge being excluded.

        for (int j = 0; j < 112; j++) {
            const auto& ve = graph.var_edges[j];
            float total = llr_ch[j];
            for (int e : ve) total += m_cv[e];
            for (int e : ve)
                m_vc[e] = std::clamp(total - m_cv[e], -LLR_MAX, LLR_MAX);
        }

        // ---- Posterior LLR, hard decision, syndrome check ----

        uint8_t bits[112];
        for (int j = 0; j < 112; j++) {
            float L = llr_ch[j];
            for (int e : graph.var_edges[j]) L += m_cv[e];
            bits[j] = (L < 0.0f) ? 1 : 0;
        }

        bool ok = true;
        for (int i = 0; i < 56 && ok; i++) {
            int syn = 0;
            for (int e : graph.check_edges[i])
                syn ^= bits[graph.edges[e].var];
            if (syn) ok = false;
        }

        result.iterations = iter + 1;
        if (ok) {
            result.converged = true;
            for (int k = 0; k < 56; k++) result.message[k] = bits[k];
            return result;
        }
    }

    // Not converged – return best posterior estimate of the message bits.
    for (int j = 0; j < 56; j++) {
        float L = llr_ch[j];
        for (int e : graph.var_edges[j]) L += m_cv[e];
        result.message[j] = (L < 0.0f) ? 1 : 0;
    }
    return result;
}
